import {expect,test,type Page} from '@playwright/test'
import {fixture} from './fixture'
const stat=(page:Page,label:string)=>page.getByLabel('Ride telemetry').locator('.stat').filter({has:page.getByText(label,{exact:true})}).locator('strong')
const numeric=async(page:Page,label:string)=>parseFloat(await stat(page,label).innerText())
const start=async(page:Page)=>{
  await page.getByRole('button',{name:'Start Ride'}).click()
  await expect(page.getByText('Preparing track…')).toHaveCount(0)
  await expect(page.locator('canvas')).toBeVisible()
}
test('demo rides under real pedal, brake and pause controls',async({page})=>{
  const errors:string[]=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/')
  await expect(page.getByRole('heading',{name:'Demo routes'})).toBeVisible()
  await page.getByRole('button',{name:'Try Demo'}).click()
  await expect(page.locator('canvas')).toBeVisible()
  await expect(page.getByText('Preparing track…')).toHaveCount(0)
  await page.keyboard.down('w')
  await expect.poll(()=>numeric(page,'Speed'),{timeout:5500}).toBeGreaterThan(7)
  await expect.poll(()=>numeric(page,'Game cadence')).toBeGreaterThan(10)
  await page.keyboard.up('w')
  await expect.poll(()=>numeric(page,'Game cadence')).toBe(0)
  await page.keyboard.down('s')
  await expect.poll(()=>numeric(page,'Speed')).toBeLessThan(4)
  await page.keyboard.up('s')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('heading',{name:'Paused.'})).toBeVisible()
  await page.getByRole('button',{name:'Resume'}).click()
  await page.getByRole('button',{name:'Restart'}).click()
  await expect(stat(page,'Crashes')).toHaveText('0')
  await expect(stat(page,'Progress')).toHaveText('0%')
  expect(errors).toEqual([])
})
test('FIT import disables unavailable channels and validates modes, preview, tuning and persistence',async({page})=>{
  await page.goto('/')
  await page.locator('input[type=file]').setInputFiles({name:'synthetic-workout.fit',mimeType:'application/octet-stream',buffer:Buffer.from(fixture())})
  await expect(page.getByRole('heading',{name:'synthetic-workout'})).toBeVisible()
  await expect(page.getByLabel('Terrain Source')).toHaveValue('heartRate')
  await expect(page.getByRole('option',{name:'Power',exact:true})).toBeDisabled()
  const before=await page.getByRole('img',{name:'Generated terrain profile'}).locator('path').last().getAttribute('d')
  await page.getByRole('button',{name:'RAW',exact:true}).click()
  await expect(page.getByRole('button',{name:'RAW',exact:true})).toHaveAttribute('aria-pressed','true')
  await page.getByLabel('Movement Mode').selectOption('data')
  await page.getByLabel('Assist Metric').selectOption('speed')
  await expect(page.getByLabel('Speed Multiplier')).toBeEnabled()
  await page.getByLabel('Movement Mode').selectOption('assist')
  await expect(page.getByLabel('Speed Multiplier')).toBeDisabled()
  await page.getByLabel('Preset').selectOption('Hard')
  await expect(page.getByRole('img',{name:'Generated terrain profile'}).locator('path').last()).not.toHaveAttribute('d',before!)
  await page.getByRole('checkbox',{name:/Debug overlay/}).check()
  await start(page)
  await expect(page.locator('.debug')).toContainText('Torque')
  await page.reload()
  await page.getByRole('button',{name:'Track Lab',exact:true}).click()
  await expect(page.getByLabel('Preset')).toHaveValue('Hard')
})
test('selects a new terrain source and crosses the finish from the last section',async({page})=>{
  await page.goto('/')
  await page.getByRole('button',{name:'Track Lab',exact:true}).click()
  await page.getByLabel('Terrain Source').selectOption('cadence')
  await page.getByLabel('Start position').press('End')
  await start(page)
  await page.keyboard.down('ArrowUp')
  await expect(page.getByRole('heading',{name:'Finished!'})).toBeVisible({timeout:9000})
  await page.keyboard.up('ArrowUp')
  await expect(stat(page,'Progress')).toHaveText('100%')
  await page.getByRole('button',{name:'Ride Again'}).click()
  await expect(stat(page,'Progress')).toHaveText('99%')
})

